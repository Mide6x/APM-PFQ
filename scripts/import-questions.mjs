import assert from "node:assert/strict";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export function validateQuestionBatches(batches, lessons) {
  const known = new Map(lessons.map(lesson => [lesson.id, lesson]));
  const ids = new Set(), stems = new Set(), batchIds = new Set();
  const questions = [];
  const text = value => typeof value === "string" && value.trim().length > 0;
  const normalise = value => value.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, " ").trim();
  for (const batch of batches) {
    assert.ok(text(batch.batch) && !batchIds.has(batch.batch), "Missing or duplicate batch ID");
    batchIds.add(batch.batch);
    assert.ok(Array.isArray(batch.questions) && batch.questions.length, "Batch has no questions");
    for (const q of batch.questions) {
      assert.match(q.id ?? "", /^PFQ-[0-9]{4,6}$/, "Invalid question ID");
      assert.ok(!ids.has(q.id), `Duplicate ID ${q.id}`);
      assert.ok(text(q.stem) && !stems.has(normalise(q.stem)), `Missing or duplicate stem ${q.id}`);
      assert.ok(text(q.title) && q.title.length <= 160, `Invalid title ${q.id}`);
      assert.ok(known.has(q.lessonId), `Unknown topic ${q.id}`);
      assert.ok(Number.isSafeInteger(q.version) && q.version > 0, `Invalid version ${q.id}`);
      assert.equal(typeof q.published, "boolean", `Missing publication state ${q.id}`);
      assert.ok(["Easy", "Medium", "Hard", "Very hard"].includes(q.difficulty), `Invalid difficulty ${q.id}`);
      assert.ok(Array.isArray(q.requiredLessonIds) && q.requiredLessonIds.includes(q.lessonId) &&
        new Set(q.requiredLessonIds).size === q.requiredLessonIds.length && q.requiredLessonIds.every(id => known.has(id)), `Invalid lesson requirements ${q.id}`);
      const refs = new Set(q.requiredLessonIds.flatMap(id => known.get(id).syllabusRefs));
      assert.ok(Array.isArray(q.syllabusRefs) && q.syllabusRefs.length && new Set(q.syllabusRefs).size === q.syllabusRefs.length &&
        q.syllabusRefs.every(ref => refs.has(ref)), `Unknown or unmapped syllabus reference ${q.id}`);
      assert.ok(Array.isArray(q.choices) && q.choices.length === 4, `Need four choices ${q.id}`);
      assert.ok(q.choices.every(c => typeof c.id === "string" && /^[a-z][a-z0-9-]{0,39}$/.test(c.id) && text(c.text)), `Invalid choices ${q.id}`);
      assert.equal(new Set(q.choices.map(c => c.id)).size, 4, `Duplicate choice ID ${q.id}`);
      assert.equal(new Set(q.choices.map(c => normalise(c.text))).size, 4, `Duplicate choice text ${q.id}`);
      assert.ok(q.choices.some(c => c.id === q.correctOptionId) && text(q.explanation), `Missing answer/explanation ${q.id}`);
      ids.add(q.id); stems.add(normalise(q.stem)); questions.push(q);
    }
  }
  return questions;
}

export function generateQuestionSeed(questions, lessons) {
  const quote = value => `'${String(value).replaceAll("'", "''")}'`;
  let sql = "-- Generated by node scripts/import-questions.mjs. Original reviewed batch content.\n-- Apply after migration 006. Existing catalogue and learner records are preserved.\nbegin;\n";
  for (const q of questions) {
    const lesson = lessons.find(lesson => lesson.id === q.lessonId);
    sql += `insert into public.practice_questions as current (id,module_id,title,difficulty,syllabus_refs,content_version,published)\nselect ${quote(q.id)},id,${quote(q.title)},${quote(q.difficulty)},array[${q.syllabusRefs.map(quote).join(",")}],${q.version},${q.published} from public.study_modules where guide_section=${quote(lesson.guideSection)}\non conflict(id) do update set module_id=excluded.module_id,title=excluded.title,difficulty=excluded.difficulty,syllabus_refs=excluded.syllabus_refs,content_version=excluded.content_version,\npublished=case when current.content_version<excluded.content_version then excluded.published else current.published end where current.content_version<=excluded.content_version;\n`;
    sql += `insert into apm_private.practice_question_content as current (question_id,content_version,stem,choices,correct_option_id,explanation)\nvalues(${quote(q.id)},${q.version},${quote(q.stem)},${quote(JSON.stringify(q.choices))}::jsonb,${quote(q.correctOptionId)},${quote(q.explanation)})\non conflict(question_id) do update set content_version=excluded.content_version,stem=excluded.stem,choices=excluded.choices,correct_option_id=excluded.correct_option_id,explanation=excluded.explanation where current.content_version<=excluded.content_version;\n`;
    sql += `delete from public.practice_question_lessons where question_id=${quote(q.id)} and exists(select 1 from public.practice_questions where id=${quote(q.id)} and content_version=${q.version});\n`;
    for (const id of q.requiredLessonIds) sql += `insert into public.practice_question_lessons(question_id,lesson_id) select ${quote(q.id)},${quote(id)} where exists(select 1 from public.practice_questions where id=${quote(q.id)} and content_version=${q.version}) on conflict do nothing;\n`;
  }
  return sql + "commit;\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const directory = new URL("../content/questions/", import.meta.url);
  const lessons = JSON.parse(readFileSync(new URL("../content/lessons.json", import.meta.url), "utf8"));
  const batches = readdirSync(directory).filter(name => name.endsWith(".json")).sort().map(name => JSON.parse(readFileSync(new URL(name, directory), "utf8")));
  const questions = validateQuestionBatches(batches, lessons);
  const seed = generateQuestionSeed(questions, lessons);
  const output = new URL("../supabase/seed_phase5.sql", import.meta.url);
  if (process.argv.includes("--check")) assert.equal(readFileSync(output, "utf8"), seed, "Question seed needs regenerating");
  else writeFileSync(output, seed);
  console.log(`Validated ${questions.length} questions across ${batches.length} batches and ${new Set(questions.map(q => q.lessonId)).size} topics; ${questions.filter(q => q.published).length} marked for publication.`);
}
